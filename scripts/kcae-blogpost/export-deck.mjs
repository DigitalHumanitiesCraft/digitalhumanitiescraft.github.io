// Turns a Google Slides API dump of the UFL workshop deck into the blog post inventory.
// The dump is the response of presentations.get with the field mask
//   title,revisionId,slides(objectId,pageElements(shape(placeholder(type),text(textElements(textRun(content)))),
//   table(tableRows(tableCells(text(textElements(textRun(content))))))),
//   slideProperties(notesPage(pageElements(shape(text(textElements(textRun(content))))))))
// The deck is only read; this script never writes to Google.
//   node scripts/kcae-blogpost/export-deck.mjs <dump.json> [outDir]
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [dumpPath, outDir = "knowledge/kcae-blogpost"] = process.argv.slice(2);
if (!dumpPath) {
  console.error("usage: node export-deck.mjs <dump.json> [outDir]");
  process.exit(2);
}
const raw = JSON.parse(readFileSync(dumpPath, "utf8"));
const deck = raw.content ?? raw;

const text = (t) => (t?.textElements ?? []).map((e) => e.textRun?.content ?? "").join("");
// Vertical tab is the Slides soft line break.
const clean = (s) => s.replace(/\u000b/g, "\n").trim();

// The Markdown slide shows its title as an image and uses the title placeholder for its definition text.
const TITLE_OVERRIDES = { h2c7fc6986ae54bd6_38_43: "Markdown" };

// The deck marks unaccepted slides with a red shape whose only text is "Entwurf".
const DRAFT = "Entwurf";

const slides = deck.slides.map((s, i) => {
  let title = "";
  const body = [];
  for (const pe of s.pageElements ?? []) {
    const t = clean(text(pe.shape?.text));
    // Section dividers carry a subtitle in a further paragraph of the title, which stays in the body.
    // A soft break inside the title is only layout.
    if (pe.shape?.placeholder?.type === "TITLE" && t && !title && !TITLE_OVERRIDES[s.objectId]) {
      const [first, ...rest] = text(pe.shape.text).replace(/\u000b/g, " ").trim().split("\n");
      title = first.trim();
      title = title.replace(/\s+/g, " ");
      if (rest.join("").trim()) body.push(rest.join("\n").trim());
    } else if (t) body.push(t);
    for (const row of pe.table?.tableRows ?? []) {
      body.push("| " + row.tableCells.map((c) => clean(text(c.text)).replace(/\n/g, " ")).join(" | ") + " |");
    }
  }
  title ||= TITLE_OVERRIDES[s.objectId] ?? "";
  // Slide 1 has no title placeholder, its first text shape carries the title.
  if (!title && body.length) title = body.shift().split("\n")[0];
  const draft = body.includes(DRAFT);
  const notes = (s.slideProperties?.notesPage?.pageElements ?? []).map((pe) => clean(text(pe.shape?.text))).filter(Boolean);
  return { n: i + 1, id: s.objectId, title, status: draft ? "draft" : "accepted", body: body.filter((b) => b !== DRAFT), notes };
});

writeFileSync(
  join(outDir, "deck-slides.json"),
  JSON.stringify({ presentation: deck.title, revisionId: deck.revisionId, slides: slides.map(({ n, id, title, status }) => ({ n, id, title, status })) }, null, 1) + "\n",
);

const fence = (s) => "````text\n" + s + "\n````";
const md = [
  "---",
  `title: "Inventory of the UFL workshop deck"`,
  `created: ${new Date().toISOString().slice(0, 10)}`,
  "status: generated",
  "related: [plan.md, deck-slides.json]",
  "---",
  "",
  "# Inventory of the UFL workshop deck",
  "",
  `Generated by \`scripts/kcae-blogpost/export-deck.mjs\` from the deck "${deck.title}" (Google Slides ID 1kl9usbbkny5hl8QOKlN_OqYZWbDPo90TaINnPTEImnE, revision ${deck.revisionId ?? "unknown"}). Do not edit by hand, regenerate after a deck change. Slide text and speaker notes stay verbatim and German. Status "draft" means the slide carries the red "Entwurf" marker.`,
  "",
  "| No. | Slide ID | Title | Status |",
  "|---|---|---|---|",
  ...slides.map((s) => `| ${s.n} | \`${s.id}\` | ${s.title.replace(/\|/g, "\\|")} | ${s.status} |`),
  "",
  ...slides.flatMap((s) => [
    `## ${s.n} ${s.title}`,
    "",
    `Slide ID \`${s.id}\`, status ${s.status}.`,
    "",
    ...(s.body.length ? [fence(s.body.join("\n\n")), ""] : []),
    ...(s.notes.length ? ["Speaker notes:", "", fence(s.notes.join("\n\n")), ""] : []),
  ]),
].join("\n");
writeFileSync(join(outDir, "deck-inventory.md"), md);
console.log(`${slides.length} slides, ${slides.filter((s) => s.status === "draft").length} draft`);
